def mv(sts, ddx=0.0, ddy=0.0, sx=1.0, sy=1.0, cx=0.0, cy=0.0):
    return [[((x - cx) * sx + cx + ddx, (y - cy) * sy + cy + ddy) for x, y in s] for s in sts]

def rot(sts, cx, cy):
    """Demi-tour autour de (cx, cy)."""
    return [[(2 * cx - x, 2 * cy - y) for x, y in s] for s in sts]

def miroir(sts, cx):
    return [[(2 * cx - x, y) for x, y in s] for s in sts]

def cercle(cx, cy, r, n=24, a0=90.0):
    a = np.radians(a0 + 360.0 * np.arange(n + 1) / n)
    return [(cx + r * np.cos(t), cy + r * np.sin(t)) for t in a]

def point(cx, cy, r=12):
    """Point à la craie : une petite boucle serrée qui se remplit."""
    return [(cx - 0.5 * r, cy - r), (cx + 0.8 * r, cy - 0.7 * r), (cx + r, cy + 0.5 * r), (cx, cy + r),
            (cx - 0.9 * r, cy + 0.4 * r), (cx - 0.7 * r, cy - 0.5 * r), (cx + 0.3 * r, cy - 0.3 * r)]

