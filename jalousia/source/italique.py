PENTE = 12          # degrés
Y0 = XH / 2         # on penche autour du milieu de la hauteur d'x

def penche(sts, a=PENTE):
    t = math.tan(math.radians(a))
    return [[(x + t * (y - Y0), y) for x, y in s] for s in sts]

def sortie(x, y=0):
    """Fin de fût qui part vers la droite (remplace le pied)."""
    return [(x - 2, y + 150), (x + 12, y + 40), (x + 55, y), (x + 115, y + 22)]

